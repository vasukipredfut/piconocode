--
-- Plain UPDATE (not upsert) -- only touches a sku_code that already has a
-- row in m5_sku_master; a code not yet in the catalog is silently skipped,
-- same caveat as V271/V272 (see V273's header). Two source rows were exact
-- duplicates (SKU1224, SKU1288, same values both times) -- deduped here.
