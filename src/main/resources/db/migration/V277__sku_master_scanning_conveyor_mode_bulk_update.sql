-- spreadsheet's "Barcode no" values are mostly Excel scientific-notation
-- artifacts (e.g. "8.90001E+12") from a numeric-formatted export, not the
-- real 13-digit EAN codes -- loading these would silently corrupt the real
-- barcode data that ConveyorScanService.resolveByBarcode() depends on for
-- live conveyor scans. Re-export the source sheet with that column
